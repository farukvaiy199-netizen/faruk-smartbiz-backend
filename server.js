const webhookLimiter = rateLimit({
  windowMs: 60 * 1000,
  max: 20,
  standardHeaders: true,
  legacyHeaders: false,
  message: { error: 'অনেক বেশি রিকোয়েস্ট, একটু পরে চেষ্টা করুন' }
});

